import { expect, test } from "@playwright/test"
import { signInAs } from "./support"

test("Home connects the animated Acuity mark to three keyboard-accessible areas", async ({ page }, testInfo) => {
  await signInAs(page, "selected@abita.test", "Synthetic Staff", "/workspace")
  const connections = page.getByRole("group", { name: "Agent connections" })
  const breadcrumbs = page.getByRole("navigation", { name: "Current location" })
  await expect(breadcrumbs).toHaveText("Home")
  const sidebar = page.locator('[data-slot="sidebar-inner"]')
  const picker = sidebar.getByRole("button", { name: "Workspace selector" })
  await expect(picker).toBeVisible()
  await expect(sidebar.getByRole("textbox")).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Workspace selector" })).toHaveCount(1)
  const homeIcon = page.getByRole("navigation", { name: "Workspace" }).getByRole("button", { name: "Home", exact: true })
  await expect(page.getByRole("navigation", { name: "Workspace" })).toHaveCSS("row-gap", "12px")
  await expect(homeIcon).toHaveText("")
  const brand = await sidebar.getByText("Acuity Health", { exact: true }).boundingBox()
  await expect(page.getByRole("heading", { level: 1 })).not.toHaveText("Your agent")
  await expect(page.locator("time[datetime]").first()).toHaveText(/\w+ \w+ \d+(st|nd|rd|th) \d{4}/)
  await page.getByRole("navigation", { name: "Workspace" }).getByRole("button", { name: "Work", exact: true }).click()
  await expect(sidebar.getByRole("group", { name: "Workspace folders" })).toBeVisible()
  const workBrand = await sidebar.getByText("Acuity Health", { exact: true }).boundingBox()
  expect(workBrand?.x).toBe(brand?.x)
  expect(workBrand?.y).toBe(brand?.y)
  await homeIcon.click()
  await expect(connections).toBeVisible()
  const homeBox = await homeIcon.boundingBox()
  expect(brand).not.toBeNull()
  expect(homeBox).not.toBeNull()
  expect(Math.abs(homeBox!.y + homeBox!.height / 2 - brand!.y - brand!.height / 2)).toBeLessThanOrEqual(2)
  await homeIcon.hover()
  await expect(page.locator('[data-slot="tooltip-content"]').filter({ hasText: /^Home$/ })).toBeVisible()
  await page.mouse.move(600, 600)
  const mark = connections.getByRole("img", { name: "Acuity", exact: true })
  await expect(connections.getByRole("button")).toHaveCount(3)
  await expect(mark.locator("circle")).toHaveCount(7)
  await expect(mark.locator("..")).toHaveCSS("border-top-width", "0px")
  await expect(page.getByText("Your office’s AI agent", { exact: true })).toHaveCount(0)
  await expect(page.getByText(/Transfer policy|Emergency policy/)).toHaveCount(0)
  const firstFrame = await mark.innerHTML()
  await expect.poll(() => mark.innerHTML()).not.toBe(firstFrame)
  await page.screenshot({ path: testInfo.outputPath("agent-home-desktop.png"), fullPage: true })

  const tools = connections.getByRole("button", { name: "Tools", exact: true })
  await tools.focus()
  await page.keyboard.press("Enter")
  await expect(tools).toHaveAttribute("aria-expanded", "true")
  await expect(page.getByRole("list", { name: "Agent tools" })).toBeVisible()
  await page.getByRole("button", { name: "Close details", exact: true }).click()
  await expect(tools).toBeFocused()
  await expect(tools).toHaveAttribute("aria-expanded", "false")

  await connections.getByRole("button", { name: "Knowledge base", exact: true }).click()
  await page.getByRole("button", { name: "Open knowledge base", exact: true }).click()
  await expect(page.getByRole("heading", { level: 1, name: "Knowledge base" })).toBeVisible()
  await expect(breadcrumbs.locator('[aria-current="page"]')).toHaveText("Knowledge base")
  await expect(picker).toBeVisible()
  await expect(page.getByRole("button", { name: "Workspace selector" })).toHaveCount(1)
  await page.screenshot({ path: testInfo.outputPath("agent-knowledge-breadcrumb.png"), fullPage: true })
  await breadcrumbs.getByRole("button", { name: "Home", exact: true }).click()
  await connections.getByRole("button", { name: "Insurance", exact: true }).click()
  await page.getByRole("button", { name: "Open insurance list", exact: true }).click()
  await expect(page.getByRole("heading", { level: 1, name: "Insurance list" })).toBeVisible()
  await expect(breadcrumbs.locator('[aria-current="page"]')).toHaveText("Insurance list")
  await expect(picker).toBeVisible()
  await expect(page.getByRole("button", { name: "Workspace selector" })).toHaveCount(1)
})

test("Home fits narrow screens and honors reduced motion", async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.setViewportSize({ width: 390, height: 844 })
  await signInAs(page, "selected@abita.test", "Synthetic Staff", "/workspace")
  const connections = page.getByRole("group", { name: "Agent connections" })
  const mark = connections.getByRole("img", { name: "Acuity", exact: true })
  await expect(mark).toBeVisible()
  const frame = await mark.innerHTML()
  await connections.getByRole("button", { name: "Tools", exact: true }).click()
  await expect(page.getByRole("list", { name: "Agent tools" })).toBeVisible()
  await expect(mark).toHaveJSProperty("innerHTML", frame)
  await page.getByRole("button", { name: "Close details", exact: true }).click()
  await page.getByRole("heading", { level: 1 }).scrollIntoViewIfNeeded()
  for (const width of [390, 768, 1024, 1280]) {
    await page.setViewportSize({ width, height: 900 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    const cards = await connections.getByRole("button").all()
    for (const card of cards) {
      await expect(card).toBeVisible()
      expect(await card.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    }
    await page.screenshot({ path: testInfo.outputPath(`agent-home-${width}.png`), fullPage: true })
  }
})

test("Home and scoped pages share one sidebar office picker on phones", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await signInAs(page, "admin@abita.test", "Fixture Admin", "/workspace")
  const picker = page.getByRole("button", { name: "Workspace selector" })
  const homeRail = page.getByRole("navigation", { name: "Workspace", exact: true }).getByRole("button", { name: "Home", exact: true })
  const breadcrumbs = page.getByRole("navigation", { name: "Current location", exact: true })
  await expect(picker).toHaveCount(0)
  await expect(page.getByText("Choose an office", { exact: true })).toHaveCount(0)
  await homeRail.click()
  await expect(picker).toBeVisible()
  await expect(picker).toHaveAttribute("title", /All offices/)
  await expect(page.getByRole("dialog", { name: "Sidebar", exact: true }).getByRole("button", { name: "Workspace selector" })).toHaveCount(1)
  await page.getByRole("navigation", { name: "Manage agent", exact: true }).getByRole("button", { name: "Home", exact: true }).click()
  await page.getByRole("group", { name: "Agent connections" }).getByRole("button", { name: "Knowledge base", exact: true }).click()
  await page.getByRole("button", { name: "Open knowledge base", exact: true }).click()
  await expect(page.getByText("Choose an office", { exact: true })).toBeVisible()
  await homeRail.click()
  await expect(picker).toBeVisible()
  await expect(picker).toHaveCount(1)
  await expect(page.getByRole("navigation", { name: "Manage agent", exact: true }).getByRole("button", { name: "Knowledge base", exact: true })).toHaveAttribute("aria-current", "page")
  await picker.click()
  await page.getByRole("button", { name: "Fixture Location 1", exact: true }).click()
  await expect(page.getByRole("heading", { level: 1, name: "Knowledge base", exact: true })).toBeVisible()
  await expect(breadcrumbs.locator('[aria-current="page"]')).toHaveText("Knowledge base")
  await expect(page.getByText("Choose an office", { exact: true })).toHaveCount(0)
  await homeRail.click()
  await expect(picker).toHaveAttribute("title", /Fixture Location 1/)
  await page.getByRole("navigation", { name: "Manage agent", exact: true }).getByRole("button", { name: "Home", exact: true }).click()
  await expect(picker).toHaveCount(0)
  await expect(page.getByRole("group", { name: "Agent connections" }).getByRole("button", { name: "Knowledge base", exact: true })).toBeEnabled()
})
